#!/usr/bin/env python3
"""Stage 7 jobs for the existing Stage 6 art processor. Missing sources stay code-drawn.
python3 tools/stage7/process_art.py --write-status
python3 tools/stage7/process_art.py --build --src art-in/stage7 --write-status
Build mode requires the Stage 6 processor's numpy/opencv/Pillow/scipy dependencies.
"""
import argparse, importlib.util, json, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parents[2]
CAST = {'s7dancer': (13, 1.25, 60000), 's7veiled': (11, 1.15, 55000), 's7asmo': (18, 2.10, 120000), 's7moir': (5, .80, 45000), 's7lan': (7, .97, 50000)}
PROPS = {'s7note':(384,64,8000),'s7column':(384,448,30000),'s7shard':(512,64,10000),'s7earth':(768,128,20000),'s7shield':(256,256,12000),'s7dust':(512,256,25000),'s7ring':(288,72,6000),'s7portal':(256,256,12000),'s7crate':(128,128,6000),'s7planks':(256,64,4000),'s7ribbon':(48,48,4000),'s7arrow':(64,8,4000),'s7veil':(128,256,12000),'s7streak':(128,24,4000)}
JOBS = {}
ROWS = []
for key,(cells,cap,filecap) in CAST.items():
    JOBS[key] = dict(kind='poses',src=key+'.src.png',chroma='magenta',rows=(cells,),chars=[dict(key=key,poses=list(range(cells)),frames=list(range(cells)),idle=0,screen_h=190,names=['pose'+str(i) for i in range(cells)],feet=set(range(cells-1)),body={cells-1},flip=set())])
    ROWS.append(dict(key=key,url=f'assets/stage7/chars/{key}.webp',atlas=f'assets/stage7/chars/{key}.json',decodedCapBytes=int(cap*2**20),fileCapBytes=filecap))
for key,(w,h,filecap) in PROPS.items():
    # Props are reviewed final individual sheets, copied by artists at their intended frame sizes.
    row=dict(key=key,url=f'assets/stage7/props/{key}.webp',decodedCapBytes=w*h*4,fileCapBytes=filecap)
    frames={'s7note':6,'s7column':3,'s7shard':4,'s7earth':6,'s7shield':2,'s7ring':2,'s7planks':8}.get(key,1)
    if frames>1: row.update(frameWidth=w//frames,frameHeight=h)
    ROWS.append(row)
for key in ['moiPortrait','lanPortrait','asmoPortrait']:
    ROWS.append(dict(key=key,url=f'assets/stage7/ui/{key}.webp',decodedCapBytes=136*136*4,fileCapBytes=4000))
for key in ['bg7far','bg7mid','bg7mid2','bg7mid3','bg7mid4','bg7floor','bg7floor2','bg7floor3']:
    floor='floor' in key; size=(1280,180) if key=='bg7floor3' else (1080,360) if floor else (1024,464)
    fmt='jpg' if floor or key=='bg7far' else 'webp'
    JOBS[key]=dict(kind='image',src=key+'.src.png',key=key,size=size,fmt=fmt)
    ROWS.append(dict(key=key,url=f'assets/bg7/{key}.{fmt}',decodedCapBytes=size[0]*size[1]*4,fileCapBytes=130000))
JOBS['story']=dict(kind='panels',src='story.src.png',chroma='magenta',grid=(2,2),panels=[dict(key=f'story7p{i}') for i in [1,2,3]],size=(1280,720))
for i in [1,2,3]:ROWS.append(dict(key=f'story7p{i}',url=f'assets/stage7/story/story7p{i}.jpg',decodedCapBytes=1280*720*4,fileCapBytes=220000))
REUSED=dict(key='s6fade',url='assets/stage6/chars/s6fade.webp',atlas='assets/stage6/chars/s6fade.json',present=True)
def write_status():
    entries=[];lines=['// Generated by tools/stage7/process_art.py. Missing files use code-drawn fallbacks.','export const PAINTED7 = Object.freeze([','  Object.freeze('+json.dumps(REUSED)+'),']
    for row in ROWS:
        present=(ROOT/row['url']).is_file() and (not row.get('atlas') or (ROOT/row['atlas']).is_file())
        if present:
            from PIL import Image
            path=ROOT/row['url']; w,h=Image.open(path).size
            assert w*h*4 <= row['decodedCapBytes'], row['key']+' decoded cap'
            assert path.stat().st_size <= row['fileCapBytes'], row['key']+' file cap'
        entries.append({**row,'present':present,'placeholder':not present,'fallback':'src/stage7-paint.js','review':'pending'})
        fields={k:v for k,v in row.items() if k in ['key','url','atlas','frameWidth','frameHeight']};fields['present']=present
        lines.append('  Object.freeze('+json.dumps(fields)+'),')
    lines.append(']);')
    (ROOT/'src/stage7-painted.js').write_text('\n'.join(lines)+'\n')
    (ROOT/'assets/stage7/ART_STATUS.json').write_text(json.dumps({'version':1,'entries':[REUSED]+entries,'clips':{'M1':'missing','M2':'missing','L1':'missing','L2':'missing','D1':'missing','D2':'missing','S7':'optional, missing'},'clipReview':'No clips shipped. Rear-view-only Riley review required before activation.'},indent=2)+'\n')
def main():
    p=argparse.ArgumentParser();p.add_argument('--src',default=str(ROOT/'art-in/stage7'));p.add_argument('--build',action='store_true');p.add_argument('--write-status',action='store_true');args=p.parse_args()
    if args.build:
        spec=importlib.util.spec_from_file_location('stage6_art',ROOT/'tools/stage6/process_art.py');module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
        module.OUT={k:('assets/bg7' if k=='bg' else 'assets/stage7/'+k) for k in ['chars','ui','props','story','bg']}
        module.JOBS=JOBS;module.BUDGET_MIB={r['key']:r['decodedCapBytes']/2**20 for r in ROWS};module.TRANSIENT={r['key'] for r in ROWS if r['key'].startswith(('story','bg'))};module.TOTAL_MIB=12
        module.main(['--src',args.src,'--out',str(ROOT)])
    if args.write_status:write_status()
    print(json.dumps({'jobs':list(JOBS),'keys':len(ROWS),'fallback':'src/stage7-paint.js'}))
if __name__=='__main__':main()
