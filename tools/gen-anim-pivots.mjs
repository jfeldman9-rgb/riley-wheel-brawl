// Per-animation originX from the trimmed atlas. Median of every frame (loops and
// one-shots), rounded to 0.005. OVERRIDES wins for a flared coat or an extended arm.
// T1 emits riley_*. T1b adds grunt_, spear_, hound_, chief_. No Whitecloaks.
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

export const OVERRIDES = Object.freeze({});
export const PIVOT_KEYS = Object.freeze(['riley', 'grunt', 'spear', 'hound', 'chief']);

const root = new URL('../', import.meta.url);
const readJSON = (path) => JSON.parse(readFileSync(new URL(path, root), 'utf8'));

function median(values) {
  const sorted = [...values].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2;
}

function roundToStep(value) {
  return Number((Math.round(value * 200) / 200).toFixed(3));
}

/** Frozen-ready map of anim key → originX. `keys` defaults to PIVOT_KEYS. */
export function generatePivots(keys = PIVOT_KEYS) {
  const map = {};
  const counts = {};
  for (const key of keys) {
    const meta = readJSON(`assets/chars/${key}.anims.json`);
    const pages = meta.pages.map((page) => readJSON(`assets/chars/${page}.json`));
    for (const anim of meta.anims) {
      const ratios = anim.frames.map((frame, i) => {
        const data = pages[anim.pages[i]].frames[frame];
        const trim = data.spriteSourceSize;
        return (trim.x + trim.w / 2) / data.sourceSize.w;
      });
      map[anim.name] = Object.prototype.hasOwnProperty.call(OVERRIDES, anim.name)
        ? OVERRIDES[anim.name]
        : roundToStep(median(ratios));
      counts[anim.name] = anim.frames.length;
    }
  }
  return { map, counts };
}

export function renderPivotModule(map) {
  const lines = Object.entries(map).map(([key, value]) => `  ${key}: ${Number(value).toFixed(3)},`);
  return `// Generated by tools/gen-anim-pivots.mjs — do not edit by hand.\nexport const ANIM_PIVOT_X = Object.freeze({\n${lines.join('\n')}\n});\n`;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const { map, counts } = generatePivots();
  writeFileSync(new URL('../src/anim-pivot.js', import.meta.url), renderPivotModule(map));
  for (const [key, value] of Object.entries(map)) console.log(`${key}\t${Number(value).toFixed(3)}\t${counts[key]}`);
}
