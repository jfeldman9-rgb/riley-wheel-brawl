import './helpers/install-location.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import {stageEnabled,stageFromQuery,maxStage} from '../src/stages.js';
import {STAGE7} from '../src/stage7-def.js';
import {callInFor} from '../src/rand-call.js';
const Q=s=>new URLSearchParams(s);
test('Stage 8 is live by default and explicit opt-outs end the campaign earlier',()=>{
 assert.equal(stageEnabled(8,Q('')),true);
 assert.equal(stageFromQuery(Q('stage=8')),8);
 assert.equal(stageFromQuery(Q('stage=8&s8=1')),8);
 assert.equal(maxStage(Q('')),8);
 assert.equal(maxStage(Q('s7=1')),8);
 assert.equal(maxStage(Q('s7=1&s8=1')),8);
 assert.deepEqual(STAGE7.next(Q('')), {stage:8,fromStage7:true,autostart:true});
 assert.deepEqual(STAGE7.next(Q('s7=0')), {stage:1,stage7Return:true});
 assert.deepEqual(STAGE7.next(Q('s8=0')), {stage:1,stage7Return:true});
 assert.deepEqual(STAGE7.next(Q('s7=1&s8=1')), {stage:8,fromStage7:true,autostart:true});
 assert.equal(STAGE7.next(Q('s8=1')).stage,8);
 assert.equal(stageEnabled(8,Q('s7=0')),false);
 assert.equal(stageEnabled(8,Q('s8=0')),false);
 assert.equal(maxStage(Q('s7=0')),6);
 assert.equal(maxStage(Q('s8=0')),7);
 assert.equal(stageFromQuery(Q('stage=8&s8=0')),1);
 assert.equal(stageFromQuery(Q('stage=7&s7=0')),1);
 assert.deepEqual([5,6,7,8].map(callInFor),['loial','rand','moilan','moilan']);
});
